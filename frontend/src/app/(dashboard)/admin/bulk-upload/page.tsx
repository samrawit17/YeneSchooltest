function getUploadSummary(result: BulkUploadResult | null) {
  if (!result) {
    return { totalRecords: 0, successfulCount: 0, failedCount: 0, skippedCount: 0 };
  }

  if (result.summary) {
    return result.summary;
  }

  return {
    totalRecords: result.totalRecords || 0,
    successfulCount: result.successfulCount || 0,
    failedCount: result.failedCount || 0,
    skippedCount: result.skippedCount || result.skippedRecords?.length || 0,
  };
}

function normalizeStudentsResponse(raw: any): StudentOption[] {
  const list = raw?.data || raw || [];
  return (Array.isArray(list) ? list : []).map((student: any) => ({
    userId: student.userId || student.id,
    studentProfileId: student.id || student.studentProfile?.id,
    name: student.user?.name || student.name || "Unnamed Student",
    studentCode: student.studentCode || student.studentProfile?.studentCode,
    className: student.className || student.studentProfile?.className,
    section: student.section || student.studentProfile?.section,
  })).filter((student: StudentOption) => student.studentProfileId);
}

function normalizeCreatedCredentials(response: any, type: CreateType): CreatedCredential[] {
  if (type === "student") {
    return response?.credentials || response?.students || [];
  }

  if (type === "staff") {
    return response?.staff || response?.credentials || [];
  }

  const parent = response?.parent || response;
  const email = parent?.email || response?.email || "";
  const username = parent?.username || response?.username;
  const temporaryPassword = response?.temporaryPassword || response?.tempPassword;

  if (!username || !temporaryPassword) {
    return [];
  }

  return [{
    name: parent?.name || response?.name || "Parent",
    email,
    username,
    temporaryPassword,
    role: "PARENT",
  }];
}

function downloadBlob(data: BlobPart, filename: string) {
  const url = window.URL.createObjectURL(new Blob([data]));
  const link = document.createElement("a");
  link.href = url;
  link.setAttribute("download", filename);
  document.body.appendChild(link);
  link.click();
  link.remove();
  window.URL.revokeObjectURL(url);
}

function normalizeStudentAndParentNames(fullName?: string, explicitParentName?: string) {
  const normalizedStudentName = String(fullName || "").replace(/\s+/g, " ").trim();
  const normalizedExplicitParentName = explicitParentName?.replace(/\s+/g, " ").trim() || "";

  if (!normalizedStudentName) {
    return { studentName: "", parentName: normalizedExplicitParentName };
  }

  if (normalizedExplicitParentName) {
    return { studentName: normalizedStudentName, parentName: normalizedExplicitParentName };
  }

  const nameParts = normalizedStudentName.split(" ").filter(Boolean);
  if (nameParts.length >= 3) {
    return {
      studentName: nameParts.slice(0, 2).join(" "),
      parentName: nameParts.slice(1).join(" "),
    };
  }

  if (nameParts.length === 2) {
    // When there's no explicit parent_name, don't derive parent from a 2-part name
    // (e.g., "John Bekele" - Bekele is just the last name, not a parent)
    if (!normalizedExplicitParentName) {
      return { studentName: normalizedStudentName };
    }
    return {
      studentName: normalizedStudentName,
      parentName: nameParts[1],
    };
  }

  return { studentName: normalizedStudentName, parentName: "" };
}

