  async function processFile(file: File) {
    setImportFile(file);
    setUploadResult(null);
    setValidationWarnings([]);
    const text = await file.text();
    const rows = text.split("\n").filter((row) => row.trim()).slice(0, 6);
    if (rows.length === 0) {
      setPreviewData([]);
      return;
    }

    const headers = rows[0].split(",").map(h => h.trim()).filter(h => h && h.toLowerCase() !== '#');
    const warnings: string[] = [];
    
    const normalizedHeaders = headers.map(h => h.toLowerCase().replace(/\s+/g, '_'));
    const hasStaffFields = normalizedHeaders.some(h => ['full_name', 'name', 'email', 'phone', 'role'].includes(h));
    const hasStudentFields = normalizedHeaders.some(h => ['first_name', 'middle_name', 'last_name', 'current_class', 'parent_name', 'parent_phone', 'gender'].includes(h));
    
    if (uploadType === 'staff' && hasStudentFields) {
      warnings.push("STUDENT_DATA_DETECTED");
    } else if (uploadType === 'students-auto' && hasStaffFields && !hasStudentFields) {
      warnings.push("STAFF_DATA_DETECTED");
    }

    const parsed = rows.slice(1).map((row) => {
      // Handle row - may have newlines/tabs within it from Excel format
      let cleanRow = row.replace(/\n/g, ' ').replace(/\t/g, ' ');
      // Collapse multiple spaces
      cleanRow = cleanRow.replace(/\s+/g, ' ').trim();
      
      let values = cleanRow.split(",").map(v => v.trim());
      // Remove leading row numbers (1, 2, 3...) - check if first value is purely numeric and remove it
      if (values.length > 0 && /^\d+$/.test(values[0])) {
        values = values.slice(1);
      }
      // Also remove empty leading values that might come from extra columns
      while (values.length > 0 && values[0] === '') {
        values = values.slice(1);
      }
      // If we have more values than headers, check if first few are single letters (likely garbage)
      while (values.length > headers.length && /^[A-Za-z]$/.test(values[0])) {
        values = values.slice(1);
      }
      const record: Record<string, string> = {};
      headers.forEach((header, index) => {
        record[header] = values[index] || "";
      });

      const studentNameKey = headers.find((header) => {
        const normalized = header.trim().toLowerCase();
        return normalized === "full_name" || normalized === "fullname" || normalized === "name" || normalized === "student_name";
      })?.trim();
      const parentNameKey = headers.find((header) => {
        const normalized = header.trim().toLowerCase();
        return normalized === "parent_name" || normalized === "parent_fullname" || normalized === "guardian_name" || normalized === "parent";
      })?.trim();

      if (studentNameKey) {
        const normalizedNames = normalizeStudentAndParentNames(
          record[studentNameKey],
          parentNameKey ? record[parentNameKey] : "",
        );
        record[studentNameKey] = normalizedNames.studentName;
        if (parentNameKey && normalizedNames.parentName) {
          record[parentNameKey] = normalizedNames.parentName;
        } else if (!parentNameKey && normalizedNames.parentName) {
          record.parent_name = normalizedNames.parentName;
        }
      }

      return record;
    });
    setPreviewData(parsed);
    setValidationWarnings(warnings);
  }

